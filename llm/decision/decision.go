// Package decision defines provider-neutral types for experimental decision
// models: answering structured questions (choice, score, boolean, box)
// against shared state in a single request.
//
// The package is a contract only; it performs no I/O and imports no provider
// module. Provider adapters (for example llm/decision/typesafe) map these
// types onto a concrete provider. The decision capability is experimental.
package decision

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"net/http"
)

// QuestionType identifies a decision question type.
type QuestionType string

const (
	QuestionTypeChoice  QuestionType = "choice"
	QuestionTypeScore   QuestionType = "score"
	QuestionTypeBoolean QuestionType = "boolean"
	QuestionTypeBox     QuestionType = "box"
)

// Input is structured question content: a string, arbitrary JSON, or null.
// The zero value marshals as null.
type Input struct {
	raw json.RawMessage
	err error
}

// StringInput returns an Input holding a JSON string.
func StringInput(s string) Input {
	b, _ := json.Marshal(s)
	return Input{raw: b}
}

// JSONInput returns an Input holding v marshaled to JSON. A marshal failure
// is surfaced when the Input itself is marshaled.
func JSONInput(v any) Input {
	b, err := json.Marshal(v)
	return Input{raw: b, err: err}
}

// RawInput returns an Input holding raw JSON. The bytes are cloned so
// later caller mutation cannot change a queued request.
func RawInput(raw json.RawMessage) Input {
	return Input{raw: bytes.Clone(raw)}
}

// NullInput returns an Input holding JSON null.
func NullInput() Input {
	return Input{raw: json.RawMessage("null")}
}

func (i Input) MarshalJSON() ([]byte, error) {
	if i.err != nil {
		return nil, i.err
	}
	if len(i.raw) == 0 {
		return []byte("null"), nil
	}
	return i.raw, nil
}

func (i *Input) UnmarshalJSON(b []byte) error {
	i.raw = bytes.Clone(b)
	i.err = nil
	return nil
}

// Question is a decision question: ChoiceQuestion, ScoreQuestion,
// BooleanQuestion, or BoxQuestion (values or pointers).
type Question interface {
	sealedQuestion()
}

// ChoiceQuestion picks one named option. Criteria maps option names to
// optional structured descriptions.
type ChoiceQuestion struct {
	Instructions *Input
	Criteria     map[string]*Input
}

func (ChoiceQuestion) sealedQuestion() {}

// ScoreQuestion rates state on ordered levels described by Criteria.
type ScoreQuestion struct {
	Instructions *Input
	Criteria     []*Input
}

func (ScoreQuestion) sealedQuestion() {}

// BooleanCriteria describes the true and false outcomes of a BooleanQuestion.
type BooleanCriteria struct {
	True  *Input
	False *Input
}

// BooleanQuestion asks a yes/no question and is answered with P(true).
// Providers may rename the type on the wire; the neutral API always calls
// it boolean.
type BooleanQuestion struct {
	Instructions *Input
	Criteria     *BooleanCriteria
}

func (BooleanQuestion) sealedQuestion() {}

// BoxQuestion locates a region in an image.
type BoxQuestion struct {
	Instructions Input
}

func (BoxQuestion) sealedQuestion() {}

// StatePart is one ordered part of the shared decision state:
// TextStatePart, JSONStatePart, or FileStatePart (values or pointers).
type StatePart interface {
	sealedStatePart()
}

// TextStatePart is sent verbatim.
type TextStatePart struct {
	Text string
}

func (TextStatePart) sealedStatePart() {}

// JSONStatePart holds raw JSON state.
type JSONStatePart struct {
	Value json.RawMessage
}

func (JSONStatePart) sealedStatePart() {}

// FileStatePart is an inline file (for example an image). Reference names
// the file within state and questions; when empty, one is generated by the
// provider adapter. InsertReference controls whether the reference text is
// placed in state at the file's position: nil inserts it unless the
// reference already occurs in state, a pointer to true forces insertion,
// and a pointer to false suppresses it (and requires an explicit Reference).
type FileStatePart struct {
	Filename        string
	MediaType       string
	Data            []byte
	Reference       string
	InsertReference *bool
}

func (FileStatePart) sealedStatePart() {}

// Answer is a decision answer: ChoiceAnswer, ScoreAnswer, BooleanAnswer,
// or BoxAnswer.
type Answer interface {
	sealedAnswer()
}

// ChoiceAnswer is the chosen option and the full probability distribution.
type ChoiceAnswer struct {
	Choice        string
	Probabilities map[string]float64
}

func (ChoiceAnswer) sealedAnswer() {}

// ScoreAnswer is the fractional score and the per-level distribution.
type ScoreAnswer struct {
	Score         float64
	Probabilities map[string]float64
}

func (ScoreAnswer) sealedAnswer() {}

// BooleanAnswer is P(true).
type BooleanAnswer struct {
	Probability float64
}

func (BooleanAnswer) sealedAnswer() {}

// BoxAnswer locates a region in the image.
type BoxAnswer struct {
	Box Box
}

func (BoxAnswer) sealedAnswer() {}

// Box is a normalized rectangle measured from the image top-left.
type Box struct {
	Top    float64
	Bottom float64
	Left   float64
	Right  float64
}

// ProviderOptions is a namespaced escape hatch for provider-specific call
// options. The outer key is the provider name (for example "typesafe").
type ProviderOptions map[string]map[string]any

// ProviderMetadata is a namespaced map of provider-specific result metadata.
// The outer key is the provider name (for example "typesafe").
type ProviderMetadata map[string]map[string]any

// CallOptions configures one Decide call.
type CallOptions struct {
	State     []StatePart
	Questions map[string]Question
	// Headers override provider headers for this call.
	Headers map[string]string
	// ProviderOptions carries provider-namespaced options.
	ProviderOptions ProviderOptions
}

// Usage carries token counts reported by the provider. Absent values stay
// nil; they are never fabricated as zeroes.
type Usage struct {
	InputTokens  *int64
	OutputTokens *int64
}

// Warning reports a non-fatal issue with a decision call.
type Warning struct {
	Type    string
	Feature string
}

// Rounding declares the provider's display rounding; values are not altered.
type Rounding struct {
	ProbabilityDecimals int
	ScoreDecimals       int
}

// ResponseMetadata carries metadata about the provider HTTP response.
type ResponseMetadata struct {
	ModelID string
	Headers http.Header
	Body    json.RawMessage
}

// Result is the outcome of one Decide call.
type Result struct {
	Answers          map[string]Answer
	Rounding         Rounding
	Usage            *Usage
	Warnings         []Warning
	ProviderMetadata ProviderMetadata
	Response         ResponseMetadata
}

// UnsupportedQuestionTypeError is returned by adapters when a call contains
// a question type the underlying model does not support. It is produced
// before any I/O.
type UnsupportedQuestionTypeError struct {
	QuestionID string
	Type       QuestionType
}

func (e *UnsupportedQuestionTypeError) Error() string {
	return fmt.Sprintf("decision: question %q has unsupported type %q", e.QuestionID, e.Type)
}

// Client is the provider-neutral interface for decision models.
type Client interface {
	// Decide answers every question in opts.Questions against opts.State in
	// a single call.
	Decide(ctx context.Context, opts CallOptions) (*Result, error)
	// SupportedQuestionTypes reports the question types the underlying
	// model accepts.
	SupportedQuestionTypes() []QuestionType
}
